// Deterministic package metadata and test harness, owned by acceptance controller.
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
export function productDocs(app, pack = null) {
  fs.mkdirSync(path.join(app, "tests"), { recursive: true });
  fs.writeFileSync(
    path.join(app, "CHANGELOG.md"),
    "# Changelog\n\n## 0.1.0 — local candidate\n\nInitial issue-tracker application with project/task management, Kanban, SQLite, REST, validation and activity. Independent verification and correction history live in the factory run evidence. No deployment.\n",
  );
  for (const name of ["acceptance.mjs", "app-host.mjs"])
    fs.rmSync(path.join(app, "tests", name), { force: true });
  fs.writeFileSync(
    path.join(app, "tests", "README.md"),
    "Run the trusted factory harness from software-factory: node factory/acceptance.mjs APP_PATH EVIDENCE_DIR. This requires the rootless Workcell image and daemon. Candidate files never supply the test oracle.\n",
  );
  const harnessFiles = [
    "acceptance.mjs",
    "workcell-image/browser-check.mjs",
    "workcell.mjs",
  ];
  fs.writeFileSync(
    path.join(app, "tests", "contract.json"),
    JSON.stringify(
      {
        owner:
          "trusted software-factory factory checkout; candidate-local copies are not authoritative",
        api: "node factory/acceptance.mjs APP_PATH EVIDENCE_DIR",
        browser: "node factory/browser-acceptance.mjs APP_PATH REPORT_PATH",
        execution:
          "Rootless Workcell only; disposable database per lease; repeated before release",
        sources: harnessFiles.map((file) => ({
          path: "factory/" + file,
          sha256: createHash("sha256")
            .update(fs.readFileSync(path.join(import.meta.dirname, file)))
            .digest("hex"),
        })),
      },
      null,
      2,
    ) + "\n",
  );
  fs.writeFileSync(
    path.join(app, "package.json"),
    JSON.stringify(
      {
        name: "factory-01-issue-tracker",
        version: "0.1.0",
        private: true,
        type: "module",
        engines: { node: ">=26.12.1" },
        scripts: {
          start: "node server.mjs",
          build: "node build.mjs",
        },
      },
      null,
      2,
    ) + "\n",
  );
  fs.writeFileSync(
    path.join(app, "build.mjs"),
    `import fs from 'node:fs';\nimport {spawnSync} from 'node:child_process';\nimport {createHash} from 'node:crypto';\nconst files=['server.mjs',...(fs.existsSync('db.mjs')?['db.mjs']:[]),'public/app.js'];\nfor(const p of files){const r=spawnSync(process.execPath,['--check',p],{stdio:'inherit'});if(r.status!==0)process.exit(1);}\nconsole.log(JSON.stringify({ok:true,format:'dependency-free Node ESM and static assets',files:files.map(p=>({path:p,sha256:createHash('sha256').update(fs.readFileSync(p)).digest('hex')}))}));\n`,
  );
  fs.writeFileSync(
    path.join(app, "README.md"),
    `# Factory 01 issue tracker\n\nA dependency-free local team issue tracker generated by canonical Chain of Command roles. Node 26.12.1 or newer. No installation hooks or third-party app packages.\n\n## Run\n\nHost execution below is for manually reviewed, trusted source only. Use the factory Workcell harness for untrusted candidates.\n\n\`npm start\` or \`node server.mjs\`. Set PORT (default 4381) and DB_PATH (default ./issues.sqlite). Open http://127.0.0.1:4381. SQLite persists across restarts. Keep your database outside a replaceable build directory when upgrading.\n\nUse project controls to create, edit or delete projects. Task dialogs support title, description, priority, assignee and status. Board lanes are todo, doing and done; edit status to move a task without dragging. Activity shows changes for the selected project. Deleting a project cascades its tasks and activity.\n\n## Test and production candidate\n\n\`node factory/acceptance.mjs APP_PATH EVIDENCE_DIR\` from the trusted software-factory checkout runs 30 REST, validation, activity, cascade, static-serving and restart-persistence checks against a rootless Workcell lease. The factory also runs browser and syntax checks inside Workcell; candidate code never executes on the controller host. \`npm run build\` syntax-checks the runtime and emits checksums for the JavaScript runtime files; no transpilation is necessary. The factory copies exactly reviewed/tested source into its build directory and records SHA-256 digests in artifacts/release.json. Browser tests are run by the factory's Playwright harness before release and retained beside the candidate.\n\n## REST\n\nGET/POST /api/projects, PATCH/DELETE /api/projects/:id; GET/POST /api/tasks, PATCH/DELETE /api/tasks/:id; GET /api/activity?projectId=N; GET /api/health. Task fields: projectId, title, description, status (todo/doing/done), priority (low/medium/high), assignee. Lists return arrays, mutations return objects; errors use {error:string}. Requests must use loopback Host; cross-origin browser writes are rejected.\n\n## Limits\n\nSingle local operator, no authentication or public-hosting qualification. Do not expose the port externally. Local host execution is not a security sandbox. Never treat a successful model review as a substitute for acceptance checks.\n`,
  );
  if (pack) {
    const packHash = createHash("sha256")
      .update(JSON.stringify(pack))
      .digest("hex");
    const metadata = JSON.parse(
      fs.readFileSync(path.join(app, "package.json"), "utf8"),
    );
    metadata.name = pack.id;
    fs.writeFileSync(
      path.join(app, "package.json"),
      JSON.stringify(metadata, null, 2) + "\n",
    );
    fs.writeFileSync(
      path.join(app, "README.md"),
      `# ${pack.title}\n\n${pack.contract}\n\n## Runtime\n\nNode 26 ESM with static browser assets. The factory runs candidates only inside rootless Workcell. Manually reviewed source can use npm start with PORT and DB_PATH. No deployment is authorized.\n\n## Verification\n\nFrozen software pack: ${pack.id}. SHA-256: ${packHash}. API and browser checks run independently before release and again after release review. Inspect the factory run evidence; candidate-local test files do not control approval.\n`,
    );
    fs.writeFileSync(
      path.join(app, "CHANGELOG.md"),
      "# Changelog\n\n## 0.1.0\n\nInitial local candidate. See factory evidence for review, tests and corrections.\n",
    );
    fs.writeFileSync(
      path.join(app, "tests/README.md"),
      "# Tests\n\nUse the frozen pack with factory/pack-acceptance.mjs from the trusted factory checkout. Run candidate code only inside Workcell.\n",
    );
    fs.writeFileSync(
      path.join(app, "tests/contract.json"),
      JSON.stringify(
        {
          owner: "factory controller",
          packId: pack.id,
          packHash,
          sources: [
            "pack.mjs",
            "pack-acceptance.mjs",
            "workcell-image/pack-browser.mjs",
            "workcell.mjs",
          ].map((file) => ({
            path: "factory/" + file,
            sha256: createHash("sha256")
              .update(fs.readFileSync(path.join(import.meta.dirname, file)))
              .digest("hex"),
          })),
        },
        null,
        2,
      ) + "\n",
    );
  }
}
